/**
 * AROH Verified Food Composition Reference Table
 * Single source of truth for nutrient numbers (ICMR-NIN IFCT 2017 & USDA FoodData Central).
 * 
 * Used deterministically across both frontend (portion scaling) and backend (vision & manual meal parser).
 * NO hallucinated nutrition: if an entry is matched, values are scaled mathematically.
 * If unknown, nutrient fields store null (never invented 0).
 */

export interface NutritionPer100g {
  kcal: number;
  proteinG: number;
  carbsG: number;
  fatG: number;
  fiberG: number;
  sugarsG: number | null;
  sodiumMg: number | null;
  potassiumMg: number | null;
  calciumMg: number | null;
  ironMg: number | null;
  magnesiumMg: number | null;
  zincMg: number | null;
  vitaminA_ug: number | null;
  vitaminC_mg: number | null;
  vitaminD_ug: number | null;
  vitaminB12_ug: number | null;
  folate_ug: number | null;
}

export interface NutritionRow {
  id: string;
  name: string; // Canonical name
  hindiName?: string;
  marathiName?: string;
  aliases: string[];
  category: string;
  source: 'IFCT' | 'USDA' | 'composite';
  cookingMethod?: string;
  per100g: NutritionPer100g;
  glycemicIndex?: string | number;
  isVegetarian?: boolean;
  isVegan?: boolean;
  isFastingSafe?: boolean;
}

export interface ScaledNutrients extends NutritionPer100g {
  weightG: number;
}

/**
 * Atwater general factor calculation: 4 kcal/g protein, 4 kcal/g carb, 9 kcal/g fat.
 */
export function atwaterKcal(protein: number, carbs: number, fat: number): number {
  return Math.round(protein * 4 + carbs * 4 + fat * 9);
}

/**
 * Scale per-100g nutrients to arbitrary gram weight with rigorous math.
 */
export function scaleToGrams(row: NutritionRow | { per100g: NutritionPer100g }, grams: number): ScaledNutrients {
  const g = Math.max(0, grams);
  const factor = g / 100;
  const p = row.per100g;

  const scaleVal = (val: number | null | undefined, precision: number = 1): number | null => {
    if (val === null || val === undefined) return null;
    return Number((val * factor).toFixed(precision));
  };

  return {
    weightG: Math.round(g),
    kcal: Math.round(p.kcal * factor),
    proteinG: Number((p.proteinG * factor).toFixed(1)),
    carbsG: Number((p.carbsG * factor).toFixed(1)),
    fatG: Number((p.fatG * factor).toFixed(1)),
    fiberG: Number((p.fiberG * factor).toFixed(1)),
    sugarsG: scaleVal(p.sugarsG, 1),
    sodiumMg: scaleVal(p.sodiumMg, 0),
    potassiumMg: scaleVal(p.potassiumMg, 0),
    calciumMg: scaleVal(p.calciumMg, 0),
    ironMg: scaleVal(p.ironMg, 2),
    magnesiumMg: scaleVal(p.magnesiumMg, 0),
    zincMg: scaleVal(p.zincMg, 2),
    vitaminA_ug: scaleVal(p.vitaminA_ug, 0),
    vitaminC_mg: scaleVal(p.vitaminC_mg, 1),
    vitaminD_ug: scaleVal(p.vitaminD_ug, 1),
    vitaminB12_ug: scaleVal(p.vitaminB12_ug, 2),
    folate_ug: scaleVal(p.folate_ug, 0),
  };
}

