function normalizeText(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^\w\s]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function getTokens(text: string): string[] {
  const norm = normalizeText(text);
  if (!norm) return [];
  return norm
    .split(' ')
    .map((t) => SYNONYM_MAP[t] || t)
    .filter((t) => t.length > 1);
}

/**
 * Strict token-boundary food matcher.
 * Rules:
 * 1. Exact match against canonical or any alias -> score 1.0.
 * 2. Token overlap with strict length & specificity penalty.
 * 3. Prevents "chicken tikka masala" from matching "grilled chicken breast" (ratio < 0.72).
 * 4. Prevents "egg fried rice" from matching "boiled egg" (ratio < 0.72).
 * 5. Returns null if best score < 0.72 (Do not guess!).
 */
export function findFood(query: string): NutritionRow | null {
  if (!query || typeof query !== 'string') return null;
  const qClean = normalizeText(query);
  const qTokens = getTokens(query);
  if (qTokens.length === 0) return null;

  const normalizedQueryKey = qTokens.join(' ');

  // 1. Exact canonical or alias match
  for (const row of NUTRITION_TABLE) {
    const canonNorm = normalizeText(row.name);
    const canonKey = getTokens(row.name).join(' ');
    if (qClean === canonNorm || normalizedQueryKey === canonKey) {
      return row;
    }
    for (const alias of row.aliases) {
      const aliasNorm = normalizeText(alias);
      const aliasKey = getTokens(alias).join(' ');
      if (qClean === aliasNorm || normalizedQueryKey === aliasKey) {
        return row;
      }
    }
  }

  // 2. Token-boundary matching with specificity calculation
  let bestCandidate: NutritionRow | null = null;
  let bestScore = 0;

  for (const row of NUTRITION_TABLE) {
    const candidateAliases = [row.name, ...row.aliases];

    for (const alias of candidateAliases) {
      const aTokens = getTokens(alias);
      if (aTokens.length === 0) continue;

      // Count overlapping tokens (after synonym mapping)
      let matches = 0;
      for (const qt of qTokens) {
        if (aTokens.includes(qt)) {
          matches++;
        }
      }

      if (matches === 0) continue;

      // Specificity score: penalizes query words that don't belong to the candidate
      // AND candidate words that don't belong to the query.
      // Score = matches / max(qTokens.length, aTokens.length)
      const maxLen = Math.max(qTokens.length, aTokens.length);
      const score = matches / maxLen;

      if (score > bestScore) {
        bestScore = score;
        bestCandidate = row;
      }
    }
  }

  // Strict threshold: must be >= 0.72 to prevent partial phrase hijacking
  if (bestScore >= 0.72) {
    return bestCandidate;
  }

  return null;
}

