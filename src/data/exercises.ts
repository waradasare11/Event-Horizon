/**
 * Filter exercises based on trainee's equipment setup, pull-up bar access, target muscles, and injury history.
 * Guarantees that bodyweight_only NEVER returns dumbbell or weighted exercises.
 */
export function getRecommendedExercises(
  userEquipment: EquipmentType = 'full_gym',
  categoryFilter?: string,
  searchQuery?: string,
  injuries: string[] = [],
  hasPullUpBar: boolean = true
): ExerciseLibraryItem[] {
  return EXERCISE_LIBRARY.filter((ex) => {
    // 1. Equipment compatibility filter
    if (userEquipment === 'bodyweight_only') {
      if (ex.equipmentType !== 'bodyweight_only') {
        return false;
      }
      // Strict guarantee: Exclude any exercise mentioning dumbbells, barbells, cables, or external weights
      const text = `${ex.name} ${ex.equipment}`.toLowerCase();
      if (
        text.includes('dumbbell') ||
        text.includes('barbell') ||
        text.includes('cable') ||
        text.includes('machine') ||
        text.includes('kettlebell') ||
        text.includes('weighted')
      ) {
        return false;
      }
      // If user specifies they do NOT have a pull-up bar, filter out any pull-up bar dependent movements
      if (!hasPullUpBar && ex.requiresPullUpBar) {
        return false;
      }
    } else if (userEquipment === 'pullup_bands') {
      if (
        ex.equipmentType !== 'bodyweight_only' &&
        ex.equipmentType !== 'pullup_bands'
      ) {
        return false;
      }
    } else if (userEquipment === 'dumbbells_bench') {
      if (
        ex.equipmentType !== 'bodyweight_only' &&
        ex.equipmentType !== 'dumbbells_bench' &&
        ex.equipmentType !== 'pullup_bands'
      ) {
        return false;
      }
    }

    // 2. Category filter
    if (categoryFilter && categoryFilter !== 'All' && ex.category !== categoryFilter) {
      return false;
    }

    // 3. Search query filter
    if (searchQuery && searchQuery.trim() !== '') {
      const q = searchQuery.toLowerCase();
      const matchName = ex.name.toLowerCase().includes(q);
      const matchHindi = ex.hindiTerminology ? ex.hindiTerminology.toLowerCase().includes(q) : false;
      const matchMuscle = ex.targetMuscle.toLowerCase().includes(q);
      const matchEquip = ex.equipment.toLowerCase().includes(q);
      if (!matchName && !matchHindi && !matchMuscle && !matchEquip) return false;
    }

    return true;
  });
}
