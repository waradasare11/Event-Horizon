/**
 * Fast lookup helper for Indian ingredients by name, keyword or category
 */
export function searchIndianFoodDatabase(query: string): IFCTFoodItem[] {
  const q = query.toLowerCase().trim();
  if (!q) return INDIAN_FOOD_DATABASE;

  return INDIAN_FOOD_DATABASE.filter(
    (item) =>
      item.name.toLowerCase().includes(q) ||
      item.hindiName.toLowerCase().includes(q) ||
      (item.marathiName && item.marathiName.toLowerCase().includes(q)) ||
      item.category.toLowerCase().includes(q) ||
      item.regionalOrigin.toLowerCase().includes(q) ||
      item.preparationStyle.toLowerCase().includes(q) ||
      (q === 'fasting' && item.isFastingSafe) ||
      (q === 'vrat' && item.isFastingSafe) ||
      (q === 'upwas' && item.isFastingSafe) ||
      (q === 'sabudana' && item.id.includes('sabudana')) ||
      (q === 'peanut' && item.id.includes('peanut'))
  );
}

/**
 * Calculate exact macronutrient breakdown for custom serving weight (in grams)
 */
export function calculateCustomPortionMacros(item: IFCTFoodItem, weightG: number) {
  const factor = weightG / 100;
  return {
    weightG,
    calories: Math.round(item.per100g.calories * factor),
    proteinG: Number((item.per100g.proteinG * factor).toFixed(1)),
    carbsG: Number((item.per100g.carbsG * factor).toFixed(1)),
    fatG: Number((item.per100g.fatG * factor).toFixed(1)),
    fiberG: Number((item.per100g.fiberG * factor).toFixed(1)),
    sodiumMg: Math.round(item.per100g.sodiumMg * factor),
    calciumMg: Math.round(item.per100g.calciumMg * factor),
    potassiumMg: Math.round(item.per100g.potassiumMg * factor),
    ironMg: Number((item.per100g.ironMg * factor).toFixed(2)),
    caloriesPerGram: Number((item.per100g.calories / 100).toFixed(2)),
    proteinPerGram: Number((item.per100g.proteinG / 100).toFixed(3)),
    carbsPerGram: Number((item.per100g.carbsG / 100).toFixed(3)),
    fatPerGram: Number((item.per100g.fatG / 100).toFixed(3)),
  };
}
